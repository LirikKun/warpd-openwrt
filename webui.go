//go:embed webui.html
var indexHTML string

// renderWebUI selects only trusted, built-in text. The raw embedded page stays
// Russian for legacy callers; no user-supplied language enters HTML or script.
func renderWebUI(language string) string {
	if language != "en" {
		return indexHTML
	}
	return englishWebUI.Replace(indexHTML)
}

// Match longer phrases before their shared fragments. NewReplacer makes one
// pass over the original template, so translated text is never translated again.
// All replacements are trusted source text, safe in both HTML text/attributes
// and single-quoted JavaScript literals. No backend data passes through here.
func makeEnglishWebUI(pairs ...string) *strings.Replacer {
	entries := make([][2]string, len(pairs)/2)
	for i := range entries {
		entries[i] = [2]string{pairs[i*2], pairs[i*2+1]}
	}
	sort.SliceStable(entries, func(i, j int) bool { return len(entries[i][0]) > len(entries[j][0]) })
	for i, entry := range entries {
		pairs[i*2], pairs[i*2+1] = entry[0], entry[1]
	}
	return strings.NewReplacer(pairs...)
}

